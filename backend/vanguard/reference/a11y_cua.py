"""Input-modality statistics from Reduced A11y-CUA, as a reference for Vanguard's personas.

    python -m vanguard.reference.a11y_cua [--out docs/results/a11y-cua-reference.md]

Reads the desktop interaction logs (`*.exe.json`) under VANGUARD_DATA_DIR /
a11y-cua-reduced and counts, per group (blind and low-vision users, sighted users, and
each agent under each condition), how many actions were pointer actions and which keys
were pressed. Reference statistics only: the dataset is never used for training or in
prompts (Vanguard.md, Section 4.6a), and only aggregates are reported, never sessions.

Actions counted: key_press, hotkey (keyboard); mouse_click, scroll, drag_drop (pointer).
Cursor movement and button release are not actions and are left out.
"""

import argparse
import json
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

from vanguard.settings import get_settings

KEYBOARD = {"key_press", "hotkey"}
POINTER = {"mouse_click", "scroll", "drag_drop"}
NAVIGATION_KEYS = {"Tab", "Up", "Down", "Left", "Right"}
GROUP_NAMES = {
    "BLVU": "Blind and low-vision users",
    "SU": "Sighted users",
}


@dataclass
class GroupStats:
    files: int = 0
    events: Counter = field(default_factory=Counter)
    keys: Counter = field(default_factory=Counter)

    @property
    def keyboard(self) -> int:
        return sum(self.events[name] for name in KEYBOARD)

    @property
    def pointer(self) -> int:
        return sum(self.events[name] for name in POINTER)

    @property
    def pointer_share(self) -> float:
        total = self.keyboard + self.pointer
        return self.pointer / total if total else 0.0

    @property
    def navigation_key_share(self) -> float:
        presses = self.events["key_press"]
        return sum(self.keys[key] for key in NAVIGATION_KEYS) / presses if presses else 0.0


def _event_type(record: dict) -> str | None:
    event = record.get("event")
    if isinstance(event, dict):
        return event.get("type")
    return event if isinstance(event, str) else None


def _key(record: dict) -> str | None:
    event = record.get("event")
    return event.get("key") if isinstance(event, dict) else None


def group_of(path: Path, root: Path) -> str:
    """BLVU and SU are pooled over participants; agents are split by condition."""
    parts = path.relative_to(root).parts
    if parts[0] in GROUP_NAMES:
        return GROUP_NAMES[parts[0]]
    return f"{parts[0]} ({parts[1]})" if len(parts) > 2 else parts[0]


def collect(root: Path) -> dict[str, GroupStats]:
    stats: dict[str, GroupStats] = {}
    for path in sorted(root.rglob("*.exe.json")):
        group = stats.setdefault(group_of(path, root), GroupStats())
        group.files += 1
        data = json.loads(path.read_text(encoding="utf-8"))
        for record in data if isinstance(data, list) else [data]:
            if not isinstance(record, dict):
                continue
            kind = _event_type(record)
            if kind:
                group.events[kind] += 1
            if kind == "key_press" and _key(record):
                group.keys[_key(record)] += 1
    return stats


def markdown(stats: dict[str, GroupStats]) -> str:
    lines = [
        "| Group | Log files | Keyboard actions | Pointer actions | Pointer share "
        "| Tab and arrow share of key presses |",
        "|---|---|---|---|---|---|",
    ]
    for name, group in stats.items():
        lines.append(
            f"| {name} | {group.files} | {group.keyboard} | {group.pointer} "
            f"| {group.pointer_share:.1%} | {group.navigation_key_share:.1%} |"
        )
    lines += [
        "",
        "Source: Reduced A11y-CUA (CC BY 4.0), desktop interaction logs. Keyboard actions are "
        "key presses and hotkeys; pointer actions are clicks, scrolls and drags. Aggregates "
        "only. Generated by `python -m vanguard.reference.a11y_cua`.",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="a11y_cua")
    parser.add_argument("--root", type=Path, default=None)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)
    root = args.root or Path(get_settings().data_dir) / "a11y-cua-reduced"
    table = markdown(collect(root))
    if args.out:
        args.out.write_text(table + "\n", encoding="utf-8")
    print(table)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
