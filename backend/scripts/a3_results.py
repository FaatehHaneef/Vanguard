"""Regenerate the A3 results from the run store: python scripts/a3_results.py

Writes docs/results/a3-results.md. Every number is computed by code from the stored runs,
steps and labels (vanguard.checker, vanguard.metrics, vanguard.failures, vanguard.labels).
"""

from collections import defaultdict

from vanguard import failures, labels, results
from vanguard.metrics import GroupMetrics, group_metrics, percentile
from vanguard.settings import REPO_ROOT, Settings
from vanguard.store import RunStore

# The A3 comparison: short tasks only (Vanguard.md 4.9, model budget), 12-step cap.
COMPARISON_BATCHES = ("a3-api-cheapest", "a3-api-callback")
# Every A3 run with the real model, for the failure analysis.
ALL_BATCHES = (
    "a3-tallowmere", "a3-willowbrook", "a3-tm-buy-two", "a3-tm-cheapest", "a3-wb-book",
    "a3-wb-callback", "a3-tm-cog", "a3-wb-cog", "a3-tm-knock-gate", "a3-wb-knock-gate",
    *COMPARISON_BATCHES,
)  # fmt: skip
# Paid list price per million tokens, for a cost estimate (the runs used the free tier).
PRICE_IN, PRICE_OUT = 0.75, 3.75
PRICE_NOTE = (
    "Gemini Flash paid list price, $0.75 input and $3.75 output per million tokens "
    "(ai.google.dev pricing, read 2026-11-22; doubles on 2027-01-01)"
)


def pct(x: float) -> str:
    return f"{x:.0%}"


def ci(rate: float, interval: tuple[float, float]) -> str:
    return f"{pct(rate)} ({pct(interval[0])}–{pct(interval[1])})"


def comparison(store: RunStore, settings: Settings) -> tuple[list[GroupMetrics], dict]:
    scored = []
    tokens = defaultdict(int)
    latencies = []
    for batch_id in COMPARISON_BATCHES:
        for summary in store.list_runs(batch_id, limit=1000):
            steps = store.steps(summary.id)
            _, metrics = results.score(summary, steps, settings)
            scored.append((summary, metrics, steps))
            tokens["in"] += metrics.input_tokens
            tokens["out"] += metrics.output_tokens
            tokens["runs"] += 1
            tokens["steps"] += len(steps)
            latencies += [step.latency_ms for step in steps]
    tokens["p50"] = percentile(latencies, 50)
    tokens["p95"] = percentile(latencies, 95)
    return group_metrics(scored), tokens


def main() -> None:
    settings = Settings()
    store = RunStore(settings.database_url)
    store.create_schema()
    groups, totals = comparison(store, settings)
    lines = [
        "# A3 results (generated)",
        "",
        "Generated by `backend/scripts/a3_results.py` from the run store. Model: "
        "gemini-3.6-flash (free tier). Sites: Tallowmere (dev) and Willowbrook (test). "
        "Leakage is decided by code; the control persona (unrestricted) is scored as if "
        "every limit applied, which gives the reference rate.",
        "",
        "## 1. Prompt-only vs gate (baseline comparison)",
        "",
        "Tasks: Tallowmere `cheapest`, Willowbrook `wb-callback`; "
        f"{min(g.runs for g in groups)} runs per group; 12-step cap. "
        "Percentages in brackets are 95% Wilson intervals.",
        "",
        "| Persona / task / enforcement | Runs | Success | Runs with an executed leak "
        "| Attempted / step | Executed / step | Steps | Refused | Step p50 / p95 (s) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for g in groups:
        persona, task, option, _ = g.key.split("/")
        lines.append(
            f"| {persona} / {task} / {option} | {g.runs} | {ci(g.success_rate, g.success_ci)} "
            f"| {ci(g.any_leak_rate, g.any_leak_ci)} | {g.mean_attempted_leak_rate:.2f} "
            f"| {g.mean_executed_leak_rate:.2f} | {g.mean_steps:.1f} | {g.mean_blocked:.1f} "
            f"| {g.latency_p50_ms / 1000:.1f} / {g.latency_p95_ms / 1000:.1f} |"
        )
    cost = (totals["in"] * PRICE_IN + totals["out"] * PRICE_OUT) / 1_000_000
    runs = totals["runs"] or 1
    lines += [
        "",
        "## 2. Latency and cost",
        "",
        f"- {totals['runs']} runs, {totals['steps']} steps (one model call per step).",
        f"- Step latency, model call plus browser action: p50 {totals['p50'] / 1000:.1f} s, "
        f"p95 {totals['p95'] / 1000:.1f} s.",
        f"- Tokens: {totals['in']:,} input and {totals['out']:,} output in total; "
        f"{totals['in'] / max(totals['steps'], 1):,.0f} input tokens per step on average.",
        f"- Cost: $0 on the free tier. At the {PRICE_NOTE}: ${cost:.4f} in total, "
        f"${cost / runs:.5f} per run, ${cost / max(totals['steps'], 1):.6f} per step.",
    ]

    report = labels.agreement(store, "hadi", "ibrahim")
    agreed = report.get("checker_vs_agreed", {})
    lines += [
        "",
        "## 3. Labelled test set and checker agreement",
        "",
        f"- {report['overlap']} steps labelled independently by two labellers "
        "(a fixed, blind sample from the real runs; `data/labelling/a3`).",
        f"- Labeller agreement: Cohen's kappa {report.get('kappa', 0):.2f}, raw agreement "
        f"{pct(report.get('raw_agreement', 0))}.",
        f"- Checker vs the agreed labels ({agreed.get('steps', 0)} steps): kappa "
        f"{agreed.get('kappa', 0):.2f}, precision {pct(agreed.get('precision', 0))}, recall "
        f"{pct(agreed.get('recall', 0))}.",
        "- Limitation: this A3 sample is dominated by input-type cases (clicks by personas "
        "that may not click), which are unambiguous; harder information-leak cases come "
        "with the preview personas and honeytokens in A4.",
    ]

    items = []
    for batch_id in ALL_BATCHES:
        items += results.batch_failures(store, batch_id, settings)
    lines += ["", "## 4. Failures grouped by cause (all A3 runs with the real model)", ""]
    lines.append(failures.markdown(items, examples=4))
    out = REPO_ROOT / "docs" / "results" / "a3-results.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
